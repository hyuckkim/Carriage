def generate_town_name():
    # 가중치 기반 랜덤 선택 함수
    f = random.choices(list(first_char.keys()), weights=list(first_char.values()))[0]
    s = random.choices(list(second_char.keys()), weights=list(second_char.values()))[0]
    t = random.choices(list(third_char.keys()), weights=list(third_char.values()))[0]
    return f + s + t

def process_map_json(input_file, output_file):
    with open(input_file, 'r', encoding='utf-8') as f:
        data = json.load(f)
    
    if 'pack' in data and 'burgs' in data['pack']:
        burgs = data['pack']['burgs']
        used_names = set()  # 이미 사용된 이름을 저장하는 집합
        
        print(f"총 {len(burgs)}개의 마을 이름을 변경합니다...")
        for burg in burgs:
            if isinstance(burg, dict) and 'name' in burg:
                # 중복되지 않는 이름을 찾을 때까지 무한 반복
                while True:
                    new_name = generate_town_name()
                    if new_name not in used_names:
                        used_names.add(new_name)
                        burg['name'] = new_name
                        break
                
        # 변경된 데이터를 새 파일로 저장
        with open(output_file, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
        print(f"완료! 저장된 파일: {output_file}")
    else:
        print("JSON 구조가 예상과 다릅니다. 'pack' -> 'burgs' 경로를 확인하세요.")

